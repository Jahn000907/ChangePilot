class ChangeCase(Base):
    """Technical case container for one agent workflow instance (section 35)."""

    __tablename__ = "change_cases"
    __table_args__ = (
        UniqueConstraint("case_number", name="uq_change_cases_case_number"),
        UniqueConstraint("idempotency_key", name="uq_change_cases_idempotency_key"),
        CheckConstraint(
            "case_type IN ('SUPPLIER_EOL', 'QUALITY_ISSUE', 'CUSTOMER_CHANGE', "
            "'COST_REDUCTION', 'REGULATORY_CHANGE', 'MATERIAL_SUBSTITUTION')",
            name="ck_change_cases_case_type",
        ),
        CheckConstraint(
            "status IN ('RECEIVED', 'ANALYZING', 'PLANNING', 'WAITING_APPROVAL', "
            "'APPROVED', 'EXECUTING', 'COMPLETED', 'REJECTED', 'FAILED', 'CANCELLED')",
            name="ck_change_cases_status",
        ),
        Index("ix_change_cases_status", "status"),
        Index("ix_change_cases_case_type", "case_type"),
        Index("ix_change_cases_created_at", "created_at"),
        {"schema": ECM_SCHEMA},
    )

    case_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    case_number: Mapped[str] = mapped_column(String(40), nullable=False)
    case_type: Mapped[str] = mapped_column(String(40), nullable=False)
    status: Mapped[str] = mapped_column(String(30), nullable=False)
    source_type: Mapped[str] = mapped_column(String(30), nullable=False)
    raw_event: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    idempotency_key: Mapped[str] = mapped_column(String(100), nullable=False)
    created_by: Mapped[str] = mapped_column(String(100), nullable=False)
