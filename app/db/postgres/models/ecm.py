class ChangeImpact(Base):
    """One object found by one impact analysis run (v0.4 section 37).

    Re-running the analysis creates a new ``analysis_run_id`` instead of
    overwriting results, so old rows stay for audit and evaluation; the unique
    constraint only removes duplicates inside a single run.
    """

    __tablename__ = "change_impacts"
    __table_args__ = (
        # Shortened on purpose: the fully spelled out form
        # (uq_change_impacts_analysis_run_id_object_type_object_key_impact_type)
        # is 68 bytes and would be truncated by the 63 byte identifier limit.
        UniqueConstraint(
            "analysis_run_id",
            "object_type",
            "object_key",
            "impact_type",
            name="uq_change_impacts_analysis_run_object_impact",
        ),
        CheckConstraint(
            "object_type IN ('PART', 'PART_REVISION', 'ASSEMBLY', 'PRODUCT', "
            "'BOM_VERSION', 'INVENTORY', 'PURCHASE_ORDER', 'PRODUCTION_ORDER', "
            "'SALES_ORDER')",
            name="ck_change_impacts_object_type",
        ),
        CheckConstraint(
            "severity IN ('INFO', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL')",
            name="ck_change_impacts_severity",
        ),
        Index("ix_change_impacts_ecr_id", "ecr_id"),
        Index("ix_change_impacts_analysis_run_id", "analysis_run_id"),
        Index("ix_change_impacts_object_type_object_key", "object_type", "object_key"),
        Index("ix_change_impacts_severity", "severity"),
        {"schema": ECM_SCHEMA},
    )

    impact_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    ecr_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey(
            "ecm.engineering_change_requests.ecr_id",
            name="fk_change_impacts_ecr_id_engineering_change_requests",
            ondelete="RESTRICT",
        ),
        nullable=False,
    )
    analysis_run_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    object_type: Mapped[str] = mapped_column(String(40), nullable=False)
    object_key: Mapped[str] = mapped_column(String(150), nullable=False)
    impact_type: Mapped[str] = mapped_column(String(40), nullable=False)
    severity: Mapped[str] = mapped_column(String(20), nullable=False)
    reason: Mapped[str] = mapped_column(Text, nullable=False)
    evidence: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )


