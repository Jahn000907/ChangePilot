"""ECM schema models: engineering change case, request and impact analysis.

Field types, constraints and indexes follow design doc v0.4 as the single
source of truth:

- section 35: ``ecm.change_cases``
- section 36: ``ecm.engineering_change_requests``
- section 37: ``ecm.change_impacts``
- section 38: ``ecm.change_strategies``
- section 39: ``ecm.change_strategy_actions``
- section 40: ``ecm.change_reviews``
- section 41: ``ecm.engineering_change_orders``
- section 42: ``ecm.approval_records``
- section 43: ``ecm.bom_redlines``
- section 44: ``ecm.bom_redline_lines``
- section 45: ``ecm.execution_jobs``

Conventions taken from the same document:

- section 6.1: internal ids are UUID (v4, generated by the application);
- section 7: timestamps with a time zone use ``timestamptz`` and are stored in
  UTC;
- section 8: quantities and amounts use ``numeric(18, 4)``;
- section 9: JSON is only used for event payloads and analysis evidence, here
  ``raw_event`` and ``evidence`` (``jsonb``);
- section 25: ``created_at`` / ``updated_at`` are ``NOT NULL`` and default to
  ``now()`` in the database;
- section 51: business foreign keys use ``ON DELETE RESTRICT``;
- section 52: product structure identifiers such as ``subject_part_number``
  belong to Neo4j, so they are stored as business keys without a database
  foreign key.

Only real foreign keys express the case -> request -> impact chain; no extra
ORM relationship is invented beyond the document.

Constraint and index names are written out explicitly so Alembic migrations
stay reviewable and reversible.
"""

